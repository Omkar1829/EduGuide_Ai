export function categorizeJob(title, description = '') {
  const textToAnalyze = `${title || ''} ${description}`.toLowerCase();
  
  let bestCategory = 'Other';
  let bestScore = 0;
  
  for (const [category, config] of Object.entries(jobCategories)) {
    if (category === 'Other') continue;
    
    let score = 0;
    
    for (const keyword of config.keywords) {
      if (textToAnalyze.includes(keyword.toLowerCase())) {
        score += 2;
      }
    }
    
    const combinedSkills = [...config.skills, ...(config.keywords || [])];
    for (const skill of combinedSkills) {
      if (textToAnalyze.includes(skill.toLowerCase())) {
        score += 1;
      }
    }
    
    if (title) {
      const titleLower = title.toLowerCase();
      for (const keyword of config.keywords) {
        if (titleLower.includes(keyword.toLowerCase())) {
          score += 3;
        }
      }
    }
    
    if (score > bestScore) {
      bestScore = score;
      bestCategory = category;
    }
  }
  
  return bestCategory;
}

export function extractCategorySkills(category, text = '') {
  const categoryConfig = jobCategories[category];
  if (!categoryConfig) return [];
  
  const textLower = text.toLowerCase();
  const skills = [];
  
  for (const skill of categoryConfig.skills) {
    if (textLower.includes(skill.toLowerCase())) {
      skills.push(skill);
    }
  }
  
  return [...new Set(skills)];
}

export function getAllCategories() {
  return Object.keys(jobCategories);
}

export function getCategoryKeywords(category) {
  return jobCategories[category]?.keywords || [];
}

export function getCategorySkills(category) {
  return jobCategories[category]?.skills || [];
}

